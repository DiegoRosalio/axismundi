#!/usr/bin/env python3
"""Font pipeline for axismundi.

  python3 tools/fonts.py subset SRC_DIR   # needs fonttools: writes assets/fonts/*.ttf
  python3 tools/fonts.py embed            # no dependencies: writes src/ui/generated/fonts.inc

SRC_DIR must contain Inter-Regular.ttf, Inter-SemiBold.ttf and JetBrainsMono-Regular.ttf
(Inter 4.0 and JetBrains Mono 2.304, both SIL Open Font License 1.1).
The glyph set below is the single source of truth: it is used for subsetting and is
also emitted into fonts.inc as the codepoint list raylib loads at runtime.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "assets", "fonts")
OUTPUT = os.path.join(ROOT, "src", "ui", "generated", "fonts.inc")

FONTS = [
    # (file name, C identifier)
    ("Inter-Regular.ttf", "kFontInterRegular"),
    ("Inter-SemiBold.ttf", "kFontInterSemiBold"),
    ("JetBrainsMono-Regular.ttf", "kFontMonoRegular"),
]

RANGES = [
    (0x0020, 0x007E),  # ASCII
    (0x00A0, 0x00FF),  # Latin-1 (° ± ² ³ ¹ · × ÷ ...)
    (0x0391, 0x03A9),  # Greek capitals
    (0x03B1, 0x03C9),  # Greek small letters
    (0x2013, 0x2014),  # – —
    (0x2018, 0x201D),  # quotes
    (0x2022, 0x2022),  # •
    (0x2026, 0x2026),  # …
    (0x2070, 0x2070),  # ⁰
    (0x2074, 0x207F),  # ⁴-⁹ ⁺ ⁻ ⁼ ⁽ ⁾ ⁿ
    (0x2080, 0x208E),  # subscripts ₀-₉ ₊ ₋ ₌ ₍ ₎
    (0x2190, 0x2195),  # arrows
    (0x21D2, 0x21D2),  # ⇒
    (0x21D4, 0x21D4),  # ⇔
    (0x2202, 0x2202),  # ∂
    (0x2211, 0x2213),  # ∑ − ∓
    (0x221A, 0x221A),  # √
    (0x221E, 0x221E),  # ∞
    (0x2220, 0x2220),  # ∠
    (0x222B, 0x222B),  # ∫
    (0x2248, 0x2248),  # ≈
    (0x2260, 0x2260),  # ≠
    (0x2264, 0x2265),  # ≤ ≥
    (0x22C5, 0x22C5),  # ⋅
    (0x25A0, 0x25A1),  # ■ □
    (0x25B6, 0x25B6),  # ▶
    (0x25C0, 0x25C0),  # ◀
    (0x25CB, 0x25CB),  # ○
    (0x25CF, 0x25CF),  # ●
    (0x2713, 0x2713),  # ✓
    (0x2717, 0x2717),  # ✗
]


def codepoints():
    cps = []
    for lo, hi in RANGES:
        cps.extend(range(lo, hi + 1))
    return cps


def subset(src_dir):
    from fontTools import subset as fts  # noqa: imported only for this command

    os.makedirs(ASSETS, exist_ok=True)
    for name, _ in FONTS:
        options = fts.Options()
        options.layout_features = ["kern"]
        options.hinting = False
        options.desubroutinize = True
        options.notdef_outline = True
        font = fts.load_font(os.path.join(src_dir, name), options)
        sub = fts.Subsetter(options)
        sub.populate(unicodes=codepoints())
        sub.subset(font)
        out = os.path.join(ASSETS, name)
        fts.save_font(font, out, options)
        print(f"{name}: {os.path.getsize(out)} bytes")


def embed():
    lines = [
        "// Generated by tools/fonts.py embed. Do not edit by hand.",
        "// Fonts: Inter 4.0 and JetBrains Mono 2.304 (SIL Open Font License 1.1),",
        "// see assets/fonts/ for the license texts.",
        "#pragma once",
        "",
    ]
    for name, ident in FONTS:
        data = open(os.path.join(ASSETS, name), "rb").read()
        lines.append(f"static const unsigned char {ident}[] = {{")
        for i in range(0, len(data), 20):
            chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 20])
            lines.append(f"    {chunk},")
        lines.append("};")
        lines.append(f"static const int {ident}Size = {len(data)};")
        lines.append("")
    cps = codepoints()
    lines.append("// Codepoints loaded into every font atlas")
    lines.append("static const int kUiCodepoints[] = {")
    for i in range(0, len(cps), 12):
        lines.append("    " + ", ".join(f"0x{c:04x}" for c in cps[i:i + 12]) + ",")
    lines.append("};")
    lines.append(f"static const int kUiCodepointCount = {len(cps)};")
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUTPUT} ({len(cps)} codepoints)")


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "subset":
        subset(sys.argv[2])
    elif len(sys.argv) == 2 and sys.argv[1] == "embed":
        embed()
    else:
        print(__doc__)
        sys.exit(1)
